import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));

/** Resolves the short git SHA when building outside Docker (where .git is present). */
const resolveGitSha = () => {
	try {
		return execSync('git rev-parse --short HEAD', {
			cwd: root,
			encoding: 'utf8',
			stdio: ['ignore', 'pipe', 'ignore'],
		}).trim();
	} catch {
		return null;
	}
};

const gitSha = resolveGitSha();
const version =
	process.env.APP_VERSION ?? (gitSha ? `${pkg.version}+${gitSha}` : pkg.version);

const outDir = resolve(root, 'src/lib/generated');
const outFile = resolve(outDir, 'app-version.ts');

mkdirSync(outDir, { recursive: true });
writeFileSync(
	outFile,
	`/** Generated by scripts/generate-app-version.mjs — do not edit */\nexport const APP_VERSION = ${JSON.stringify(version)};\n`,
);

console.log(`[version] ${version}`);
